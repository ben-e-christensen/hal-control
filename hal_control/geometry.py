def ss_to_app(p):
    """SonicSurface.py frame -> app frame (metres)."""
    return np.asarray(p, dtype=float) - SS_ORIGIN_OFFSET


def app_to_ss(p):
    """App frame -> SonicSurface.py frame (metres)."""
    return np.asarray(p, dtype=float) + SS_ORIGIN_OFFSET


# --- refs/hal_lev_sim.py frame ("single + reflector") ----------------------
# Sim: z = 0 at the reflector, board at z = H facing down, x/y lateral.
# App: X = x_s, Y = H - z_s, Z = y_s.  (Reflection: handedness flips.)

def sim_to_app(p_sim, gap):
    p = np.asarray(p_sim, dtype=float)
    return np.stack([p[..., 0], gap - p[..., 2], p[..., 1]], axis=-1)


def app_to_sim(p_app, gap):
    p = np.asarray(p_app, dtype=float)
    return np.stack([p[..., 0], p[..., 2], gap - p[..., 1]], axis=-1)


def _grid_index(v):
    return np.rint(v / PITCH + (N_SIDE - 1) / 2).astype(int)


# Grid column (along X) and row (along Z) of each FPGA channel, 0..15.
GRID_COL = _grid_index(EMITTER_POS[:, 0])
GRID_ROW = _grid_index(EMITTER_POS[:, 2])

# hal_lev_sim raster index (row-major, row = y_s = Z, col = x_s = X, both
# increasing from the minimum) of each FPGA channel.
FPGA_TO_SIM_RASTER = GRID_ROW * N_SIDE + GRID_COL
SIM_RASTER_TO_FPGA = np.argsort(FPGA_TO_SIM_RASTER)


def sim_raster_to_fpga(values):
    """Reorder a per-emitter array from hal_lev_sim raster order to FPGA order."""
    return np.asarray(values)[FPGA_TO_SIM_RASTER]


def fpga_to_sim_raster(values):
    """Reorder a per-emitter array from FPGA order to hal_lev_sim raster order."""
    return np.asarray(values)[SIM_RASTER_TO_FPGA]
